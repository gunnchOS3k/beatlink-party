import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import test from 'node:test';
import { createRoomHttp, disconnectRoomHttp, endRoomHttp, joinRoomHttp } from './roomHttp.mjs';

test('end-room accepts only the server-issued host session', () => {
  const parties = new Map();
  const sessions = new Map();
  const created = createRoomHttp(parties, sessions, { code: 'room1', hostId: 'host-1' });
  assert.equal(created.status, 200);
  assert.equal(created.body.party.phase, 'lobby');
  assert.notEqual(created.body.hostSession, 'host-1');
  assert.equal(created.body.party.hostSession, undefined);
  const joined = joinRoomHttp(parties, 'room1', 'guest-2');
  assert.equal(joined.status, 200);
  assert.equal(joined.body.hostSession, undefined);
  assert.deepEqual(joined.body.party.members.map((member) => member.id), ['host-1', 'guest-2']);
  const left = disconnectRoomHttp(parties, 'room1', 'guest-2');
  assert.equal(left.status, 200);
  assert.equal(endRoomHttp(parties, sessions, 'room1', 'host-1').status, 403);
  assert.equal(endRoomHttp(parties, sessions, 'room1', 'guest-2').status, 403);
  assert.equal(endRoomHttp(parties, sessions, 'room1', '').status, 403);
  assert.equal(parties.get('ROOM1').phase, 'lobby');
  const ended = endRoomHttp(parties, sessions, 'room1', created.body.hostSession);
  assert.equal(ended.status, 200);
  assert.equal(ended.body.party.phase, 'closed');
  assert.deepEqual(ended.body.party.members, []);
  const entry = readFileSync(new URL('../index.ts', import.meta.url), 'utf8');
  assert.equal(entry.includes('httpHostSessions'), true);
  assert.equal(entry.includes('loopbackBindHost'), true);
  assert.equal(entry.includes("listen(PORT, '0.0.0.0'"), false);
  const createRoute = entry.slice(entry.indexOf("app.post('/rooms'"), entry.indexOf("app.post('/rooms/:code/join'"));
  assert.equal(createRoute.includes('req.body?.hostId'), false);
});
